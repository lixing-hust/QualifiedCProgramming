Definition qprt_preserved O O' :=
  forall dpl dpl' a n, 
    get O osdomainportid = Some (osdomainport dpl) ->
    get O' osdomainportid = Some (osdomainport dpl') ->
    (exists x2 x3 x4 x5 x6 x7 x8, get dpl a = Some (n, x2, x3, x4, x5, x6, x7, x8)) -> 
    (exists x2 x3 x4 x5 x6 x7 x8, get dpl' a = Some (n, x2, x3, x4, x5, x6, x7, x8)). 

Lemma has_port_preserved: 
  forall O pr vprt O', 
    has_port vprt O pr ->
    dom_impl O O' ->
    qprt_preserved O O' -> 
    has_port vprt O' pr.
Proof.
  introv Hhp Hdi Hqp.
  unfold has_port in *.
  destruct Hhp as [Hnull | Hid].
  -
    left; auto.
  -
    right.
    unfold port_indomainport in *.
    destruct vprt; tryfalse.
    simpljoin.
    unfolds in Hdi.
    specialize (Hdi osdomainportid).
    rewrite H in Hdi.
    destruct Hdi as (dpl & Hdi').
    lets H__: Hqp.  specializes H__; eauto.
    repeat eexists; eauto.
    simpljoin. 
    do 8 eexists.
    split; eauto.
Qed.

Lemma has_prtpost_cap_preserved:
  forall O pr O', 
    has_prtpost_cap O pr -> 
    dom_impl O O' ->
    prio_preserved O O' -> 
    get O cspaceid = get O' cspaceid -> 
    has_prtpost_cap O' pr. 
Proof.
  introv Hhpc Hdi Hpp Hcpeq.
  unfold has_prtpost_cap in *.
  simpljoin.
  rewrite <- Hcpeq.
  do 3 eexists.
  split; eauto. 
  split. eapply tps_tst_corr_preserve; eauto.
  eauto.
Qed.   

Lemma has_port_cap_preserved:
  forall v O pr O', 
    (has_port v O pr /\ has_prtpost_cap O pr) -> 
    dom_impl O O' ->
    prio_preserved O O' -> 
    qprt_preserved O O' -> 
    get O cspaceid = get O' cspaceid -> 
    (has_port v O' pr /\ has_prtpost_cap O' pr). 
Proof.
  introv Hhpc Hdi Hpp Hqp Hcpeq.
  destruct Hhpc as (Hhp & Hhc).
  split.
  eapply has_port_preserved; eauto.
  eapply has_prtpost_cap_preserved; eauto. 
Qed. 

Lemma prt_indom_cap_preserved:
  forall v O pr O', 
    prt_indom v O pr /\ has_prtpost_cap O pr ->
    dom_impl O O' ->
    prio_preserved O O' -> 
    get O cspaceid = get O' cspaceid -> 
    prt_indom v O' pr /\ has_prtpost_cap O' pr. 
Proof.
  introv Hph Hdi Hpp Hcpeq.
  destruct Hph as (Hpi & Hpc).
  split.
  - unfold prt_indom in *.
    auto.
  - eapply has_prtpost_cap_preserved; eauto.
Qed. 
  
  
