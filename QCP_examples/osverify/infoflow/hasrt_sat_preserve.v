Lemma mqdp_qref_preserve: 
  forall idx ptr O O' pr, 
    mqdes_dom_qptr idx ptr O pr -> 
    mq_ref_preserved O O' ->
    dom_impl O O' -> 
    mqdes_dom_qptr idx ptr O' pr. 
Proof.
  introv Hmdq Href Hdi.
  unfold mqdes_dom_qptr in *.
  simpljoin.
  split; auto.
  unfold spec_aux_defs.mq_ptr in *.
  simpljoin. 
  unfolds in Hdi.
  specialize (Hdi absmqattrid).
  rewrite H0 in Hdi.
  destruct Hdi as (y & Hget').
  unfolds in Href.
  lets H__: Href H0 Hget'.
  specializes H__; eauto. do 6 eexists; eauto.
  destruct H__ as (x1' & x2' & x3' & x4' & x5' & x6' & Hget'_).
  do 8 eexists; splits; eauto. 
Qed. 

Ltac eval_mq_succs Hsat :=
  match goal with 
    k: nat, H: _ = Some _ |- _ =>
      first [
          simpl in H; tryfalse; fail | 
