            solve [ simpl; auto |
                    simpl in Hsat; simpl; eapply mqdp_qref_preserve; eauto |
                    simpl in Hsat; simpl; eapply mqdd_preserve; eauto ] |
            eval_mq_succs Hsat (* on second goal generated by "destruct k" *) ]
        ]
  end.

Lemma mqsend_qref_asrt_preserve:
  forall pr cd O O', 
    (exists vl vl' k, 
        length vl = 4%nat /\ length vl' = 4%nat /\ 
          List.nth_error (get_all_succs (mqsend (vl++vl'))) k = Some cd) -> 
    head_asrt_sat pr cd O ->
