Definition mq_ref_preserved (O O': osabst) :=
  forall mqs mqs',
    get O absmqattrid = Some (absmqattr mqs) ->
    get O' absmqattrid = Some (absmqattr mqs') ->
    forall idx p,
      (exists x1 x2 x3 x4 x5 x6, get mqs idx = Some (p, x1, x2, x3, x4, x5, x6)) ->
      (exists x1 x2 x3 x4 x5 x6, get mqs' idx = Some (p, x1, x2, x3, x4, x5, x6)).

Definition port_comm_same (O O': osabst) :=
  get O osdomainportid = get O' osdomainportid /\
    get O oskportid = get O' oskportid /\
    get O oschannelid = get O' oschannelid. 

